"""Regenerate the Linux runtime version pins and bundled upstream notices."""
from importlib.metadata import distribution
from pathlib import Path
import shutil
import tomllib
from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root=Path(__file__).resolve().parents[1]
pending=list(tomllib.loads((root/'pyproject.toml').read_text())['project']['dependencies'])
found={}
environments=[]
for version in ('3.11','3.13'):
    env=default_environment()
    env.update(python_version=version,python_full_version=version+'.0',sys_platform='linux',extra='')
    environments.append(env)
while pending:
    req=Requirement(pending.pop())
    if req.marker and not any(req.marker.evaluate(env) for env in environments):
        continue
    name=canonicalize_name(req.name)
    dist=distribution(name)
    assert req.specifier.contains(dist.version), (name,dist.version,str(req.specifier))
    if name not in found:
        found[name]=dist
        pending.extend(dist.requires or [])
licenses=root/'licenses'
licenses.mkdir(exist_ok=True)
for path in licenses.glob('*.txt'):
    if path.name not in {'MPL-2.0.txt', 'CC0-1.0.txt', 'xxhash-library-LICENSE.txt'}:
        path.unlink()
rows=[]
for name,dist in sorted(found.items()):
    files=[path for path in dist.files or [] if '.dist-info/' in str(path)
           and ('license' in path.name.lower() or 'copying' in path.name.lower() or path.name.lower()=='notice')]
    assert files, f'Upstream license missing: {name}'
    links=[]
    for item in files:
        filename = item.name if item.name.endswith('.txt') else item.name + '.txt'
        target=licenses/f'{name}-{dist.version}-{filename}'
        shutil.copyfile(dist.locate_file(item),target)
        links.append(f'[{item.name}](licenses/{target.name})')
    expression=dist.metadata.get('License-Expression') or {
        'blinker':'MIT','itsdangerous':'BSD-3-Clause','jinja2':'BSD-3-Clause',
        'libarchive-c':'CC0-1.0'}.get(name) or dist.metadata.get('License')
    assert expression and len(expression)<100,(name,expression)
    if name == 'libarchive-c' and expression == 'CC0':
        expression = 'CC0-1.0'
    if name == 'defusedxml' and expression == 'PSFL':
        expression = 'PSF-2.0'
    rows.append(f'| [{dist.metadata["Name"]}](https://pypi.org/project/{name}/{dist.version}/#files) | {dist.version} | {expression} | {", ".join(links)} |')
(root/'requirements.lock').write_text('# Linux runtime versions used for the release candidate; Python 3.11 and 3.13.\n'
    '# Regenerate notices with scripts/dependency_inventory.py after changing versions.\n'
    +'\n'.join(f'{name}=={dist.version}' for name,dist in sorted(found.items()))+'\n')
(root/'THIRD_PARTY_NOTICES.md').write_text('''# Third-party notices

This project is MIT licensed. The following table inventories the separately licensed Python runtime dependencies
used to verify this release candidate. The complete license and NOTICE files from those installed distributions
are included under `licenses/` and in the wheel license metadata. Package versions are pinned in `requirements.lock`.
Names and versions refer to the upstream distributions published at https://pypi.org/.

| Distribution | Version | License identifier | Upstream license and notices |
| --- | --- | --- | --- |
'''+ '\n'.join(rows)+'''

Additional complete license texts, supplementing upstream packages that supply a license URL:

- [MPL 2.0](licenses/MPL-2.0.txt), from https://www.mozilla.org/MPL/2.0/index.txt, for certifi.
  Certifi is installed unmodified; its corresponding source distribution is available through its exact-version PyPI link above.
- [CC0 1.0 Universal](licenses/CC0-1.0.txt), from https://creativecommons.org/publicdomain/zero/1.0/legalcode.txt, for libarchive-c.
- [xxHash C library BSD license](licenses/xxhash-library-LICENSE.txt), from `deps/xxhash/LICENSE` in the xxhash source distribution.
  This supplements the Python binding's own license notice.

`libarchive-c` uses the system libarchive shared library. The Docker image installs the Debian libarchive package
and retains its license information under `/usr/share/doc/libarchive13t64/copyright`, together with the license
files supplied by Debian for its shared-library dependencies. Host installations use their system packages.
Python, pip, and the operating-system packages in the base image retain their upstream notices in that image.
These components are separate from this project's MIT-licensed source.

The inventory is generated by `scripts/dependency_inventory.py` from installed distribution metadata and license
files. After updating dependencies, regenerate it and repeat the license, package-content, and regression checks.
''')
print(f'Pinned {len(found)} runtime distributions and copied {sum(len(d.files or [])>0 for d in found.values())} distribution notice sets.')
